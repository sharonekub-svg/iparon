-- המכסה של המסלול המורחב יורדת מ-15 ל-10 העלאות בחודש.
--
-- הסיבה: ₪39 ≈ $10.5, ו-15 העלאות ב-Opus 5 עולות ~$7. מרווח כזה מתהפך
-- מכל שינוי קטן במחיר או באורך החומרים. ב-10 העלאות העלות ~$4.7.

update public.plans set max_uploads_per_month = 10 where tier = 'premium';

-- הבלם השני, ב-usage_caps, נבדק ב-Edge Function לפני כל קריאה למודל
-- והוא עצמאי מטבלת המסלולים. הוא עמד על 8, כלומר משלם היה נחסם על 8
-- אחרי שנמכרו לו 10. שתי המכסות חייבות להסכים, והנמוכה שבהן היא זו
-- שקובעת בפועל.
update public.usage_caps set max_uploads_per_user_per_month = 10 where id;
