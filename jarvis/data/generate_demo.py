def build_inbox():
    import json
    rnd2 = random.Random(SEED + 1)
    msgs = []
    for i, (addr, name, subj, body, days, unread) in enumerate(INBOX):
        when = (datetime.datetime.combine(ANCHOR, datetime.time(9, 0))
                - datetime.timedelta(days=days, hours=rnd2.randint(0, 12)))
        msgs.append({
            "id": f"m{i+1}", "from_email": addr, "from_name": name,
            "subject": subj, "body": body, "unread": unread,
            "received": when.isoformat(timespec="minutes"),
        })
    events = []
    for off, at, title, note in EVENTS:
        day = ANCHOR + datetime.timedelta(days=off)
        events.append({"date": day.isoformat(), "time": at,
                       "title": title, "note": note})
    payload = {"generated": ANCHOR.isoformat(), "seed": SEED,
               "messages": msgs, "events": events, "slipped": SLIPPED}
    with open(os.path.join(HERE, "demo_inbox.json"), "w", encoding="utf-8") as fh:
        json.dump(payload, fh, ensure_ascii=False, indent=1)
    print(f"נכתבו {len(msgs)} מיילים ו-{len(events)} אירועים ל-demo_inbox.json")


