    for (name, kind, title, body), off in zip(NOTES, offsets):
        date = ANCHOR - datetime.timedelta(days=off)
        text = (
            "---\n"
            f"title: {title}\n"
            f"type: {kind}\n"
            f"date: {date.isoformat()}\n"
            "---\n\n"
            f"# {title}\n"
            f"{body.strip()}\n"
        )
        with open(os.path.join(OUT, name + ".md"), "w", encoding="utf-8") as fh:
            fh.write(text)

    print(f"נכתבו {len(NOTES)} הערות ל-{OUT}  (seed={SEED})")
    build_inbox()


